import { mkdir, readdir, stat } from "node:fs/promises";
import { join } from "node:path";
import { A2sError, PolicyError } from "../lib/errors";
import type { TvTarget } from "../services/settings-store";
import type { SdbClient } from "../tv/sdb-client";
import { assertSafeArg, type A2sCli, type CliLogLine, type CliRun } from "./a2s-cli";
import type { JobKind, JobRunner, JobSnapshot } from "./job-runner";
import type {
  CatalogApp,
  CatalogResult,
  CertResult,
  InstalledResult,
  LeftoversResult,
  LogsResult,
  ProfileFile,
  SourcesResult,
  TvCheckResult,
} from "./types";

/** Configuration of {@link A2sService}. */
export interface A2sConfig {
  /** Where the TV is and this box's address on its network (`--local-ip`), read per command. */
  target: TvTarget;
  /** Where uploaded .wgt/.tpk files are kept until installed. */
  uploadDir: string;
  /** Where TV profiles (`tv save`) are written. */
  profileDir: string;
  /** Where signed packages (`sign`) are written for download. */
  signedDir: string;
  /** Called after anything that changes the TV's installed apps. */
  onTvAppsChanged: () => void;
  /**
   * Throws (TvUnreachableError) fast when the TV is off, so TV commands and jobs fail in
   * seconds instead of waiting for the CLI's own timeouts.
   */
  ensureTvOnline: () => Promise<void>;
}

/** What the user chose in the install dialog. */
export interface InstallRequest {
  /** Exact catalog name. */
  app: string;
  /** File or variant label (`--file`); default file when omitted. */
  file?: string;
  /** Values for the package's settings (`--set key=value`). */
  settings?: Record<string, string>;
  /** Force a Partner-level certificate. */
  partner?: boolean;
  /** Source offering the app when several do (`--from`; catalog `from`). */
  from?: string;
  /** Open the app on the TV afterwards (`--launch`). */
  launch?: boolean;
  /** Allow remove-and-reinstall when the TV refuses an in-place update; erases app data. */
  allowRemove?: boolean;
  /** Uninstall the installed copy first; erases app data (`--remove-first`). */
  removeFirst?: boolean;
  /** Install under a fresh package id (`--new-id`), for a TV that refuses the app's own id. */
  newId?: boolean;
}

/** A saved TV profile file. */
export interface TvProfile {
  name: string;
  size: number;
  modified: string;
}

/** Original arguments of a retryable job, to repeat it with `--yes`. */
interface RetryRecipe {
  kind: JobKind;
  title: string;
  args: string[];
}

/** How long the catalog is cached (it is fetched from GitHub). */
const CATALOG_CACHE_MS = 10 * 60_000;

/**
 * Leftovers go through Apps2Samsung's debug agent on the TV. Right after the agent is
 * (re)installed, its inspector may not listen yet and the CLI fails with this .NET message;
 * one retry after a short pause succeeds (verified on the M7, 2026-11-23).
 */
const AGENT_RACE = /Unable to connect to the remote server/i;

/** Pause before retrying an agent race. */
const AGENT_RETRY_DELAY_MS = 1500;

/** Install setting keys as the catalog defines them. */
const SETTING_KEY = /^[A-Za-z0-9_.-]{1,64}$/;

/** Profile names become file names. */
const PROFILE_NAME = /^[A-Za-z0-9_-]{1,64}$/;

/** Uploaded package ids (generated by the upload route). */
const UPLOAD_ID = /^[a-f0-9-]{36}\.(wgt|tpk)$/;

/**
 * "Apps2Samsung as a web service": wraps apps2samsung-cli for the dashboard.
 *
 * Every command that talks to the TV runs while m7d lends the TV's single sdb slot to the CLI
 * ({@link SdbClient.exclusive}). Long operations run as queued jobs with live logs.
 * Policy: root apps are refused and `--allow-root` / `--adult` are never passed.
 */
export class A2sService {
  private catalogCache: { apps: CatalogApp[]; fetchedAt: number } | undefined;
  private readonly retryRecipes = new Map<string, RetryRecipe>();

  constructor(
    private readonly cli: A2sCli,
    private readonly sdb: SdbClient,
    private readonly jobs: JobRunner,
    private readonly config: A2sConfig,
  ) {}

  /** Options that point a command at the TV. */
  private tvArgs(): string[] {
    return ["--tv", this.tvHost(), ...this.localIpArgs()];
  }

  /** The TV IP; refuses when none is configured. */
  private tvHost(): string {
    return this.config.target.tvHost || PolicyError.throw("No TV IP set: enter it in the dashboard's Settings");
  }

  /** `--local-ip` when this box's address is known (the CLI picks one itself otherwise). */
  private localIpArgs(): string[] {
    const ip = this.config.target.homelabIp;
    return ip ? ["--local-ip", ip] : [];
  }

  /** Runs a CLI command that uses the debug agent, retrying the agent start-up race once. */
  private runAgentCommand<T>(
    args: string[],
    options: { onLine?: (line: CliLogLine) => void; timeoutMs?: number },
  ): Promise<CliRun<T>> {
    return this.sdb.exclusive("apps2samsung-cli", async () => {
      const first = await this.cli.run<T>(args, options);
      if (!first.failure || !AGENT_RACE.test(first.failure.error)) return first;
      options.onLine?.({
        at: new Date().toISOString(),
        level: "warning",
        text: "Debug agent was not ready yet; retrying once…",
      });
      await Bun.sleep(AGENT_RETRY_DELAY_MS);
      return this.cli.run<T>(args, options);
    });
  }

  /** Runs a TV command with the sdb slot lent to the CLI. */
  private async onTv<T>(args: string[], timeoutMs?: number): Promise<CliRun<T>> {
    await this.config.ensureTvOnline();
    return this.sdb.exclusive("apps2samsung-cli", () => this.cli.run<T>(args, { timeoutMs }));
  }

  /** Returns the data of a run or throws its failure as {@link A2sError}. */
  private static unwrap<T>(run: CliRun<T>): T {
    if (run.failure || run.data === undefined) {
      return A2sError.throw(run.failure?.error ?? "apps2samsung-cli gave no answer", run.exitCode, run.failure?.details);
    }
    return run.data;
  }

  // ---- Reads -------------------------------------------------------------------------------

  /** Installable catalog apps (root apps removed by policy), cached for 10 minutes. */
  async catalog(refresh = false): Promise<CatalogApp[]> {
    const cache = this.catalogCache;
    if (!refresh && cache && Date.now() - cache.fetchedAt < CATALOG_CACHE_MS) return cache.apps;
    const result = A2sService.unwrap(await this.cli.run<CatalogResult>(["catalog"], { timeoutMs: 120_000 }));
    const apps = result.apps.filter((app) => !app.root);
    this.catalogCache = { apps, fetchedAt: Date.now() };
    return apps;
  }

  /** Apps on the TV compared with the catalog (update state per app). */
  async installed(): Promise<InstalledResult> {
    return A2sService.unwrap(await this.onTv<InstalledResult>(["installed", ...this.tvArgs()], 120_000));
  }

  /** Developer Mode / debug port / Tizen version / DUID check of the TV. */
  async tvCheck(): Promise<TvCheckResult> {
    const args = ["tv", this.tvHost(), ...this.localIpArgs()];
    return A2sService.unwrap(await this.onTv<TvCheckResult>(args, 60_000));
  }

  /** Signing certificates on this machine and whether they cover the TV. */
  async certificates(): Promise<CertResult> {
    return A2sService.unwrap(await this.cli.run<CertResult>(["cert"], { timeoutMs: 60_000 }));
  }

  /** The user's own sources (repositories, links, feeds). */
  async sources(): Promise<SourcesResult> {
    return A2sService.unwrap(await this.cli.run<SourcesResult>(["sources"], { timeoutMs: 30_000 }));
  }

  /** Adds a source; signed repositories need their key fingerprint. */
  async addSource(link: string, options: { name?: string; fingerprint?: string }): Promise<unknown> {
    const args = ["sources", "add", assertSafeArg(link, "source link")];
    if (options.name) args.push("--name", assertSafeArg(options.name, "source name"));
    if (options.fingerprint) args.push("--fingerprint", assertSafeArg(options.fingerprint, "fingerprint"), "--yes");
    const result = A2sService.unwrap(await this.cli.run<unknown>(args, { timeoutMs: 60_000 }));
    this.catalogCache = undefined;
    return result;
  }

  /** Removes a source by link or name. */
  async removeSource(linkOrName: string): Promise<unknown> {
    const args = ["sources", "remove", assertSafeArg(linkOrName, "source")];
    const result = A2sService.unwrap(await this.cli.run<unknown>(args, { timeoutMs: 30_000 }));
    this.catalogCache = undefined;
    return result;
  }

  /** Packages left in the TV's install staging folder (uses the A2S debug agent on the TV). */
  async leftovers(): Promise<LeftoversResult> {
    await this.config.ensureTvOnline();
    const run = await this.runAgentCommand<LeftoversResult>(["leftovers", ...this.tvArgs()], {
      timeoutMs: 180_000,
    });
    return A2sService.unwrap(run);
  }

  /** Saved TV profiles, newest first. */
  async profiles(): Promise<TvProfile[]> {
    await mkdir(this.config.profileDir, { recursive: true });
    const names = (await readdir(this.config.profileDir)).filter((name) => name.endsWith(".json"));
    const entries = await Promise.all(
      names.map(async (file): Promise<TvProfile> => {
        const info = await stat(join(this.config.profileDir, file));
        return { name: file.replace(/\.json$/, ""), size: info.size, modified: info.mtime.toISOString() };
      }),
    );
    return entries.sort((a, b) => b.modified.localeCompare(a.modified));
  }

  /** Contents of one saved profile (which apps a restore would install). */
  async profile(name: string): Promise<ProfileFile> {
    if (!PROFILE_NAME.test(name)) return PolicyError.throw("Unknown profile");
    const file = Bun.file(join(this.config.profileDir, `${name}.json`));
    if (!(await file.exists())) return PolicyError.throw("Unknown profile");
    return (await file.json()) as ProfileFile;
  }

  // ---- Jobs --------------------------------------------------------------------------------

  /** Queues a TV job that runs the CLI with the sdb slot lent; refreshes app state on success. */
  private async queue(
    kind: JobKind,
    title: string,
    args: string[],
    retryable: boolean,
  ): Promise<JobSnapshot> {
    await this.config.ensureTvOnline();
    const usesAgent = args[0] === "leftovers";
    const job = this.jobs.enqueue(
      kind,
      title,
      async (onLine) => {
        const run = usesAgent
          ? await this.runAgentCommand<unknown>(args, { onLine })
          : await this.sdb.exclusive("apps2samsung-cli", () => this.cli.run<unknown>(args, { onLine }));
        if (!run.failure) this.config.onTvAppsChanged();
        return run;
      },
      retryable,
    );
    if (retryable) this.retryRecipes.set(job.id, { kind, title, args });
    return job;
  }

  /** Installs a catalog app (refuses root apps). */
  async install(request: InstallRequest): Promise<JobSnapshot> {
    const app = (await this.catalog()).find((candidate) => candidate.name === request.app);
    if (!app) return PolicyError.throw(`Not an installable catalog app: ${request.app}`);
    const args = ["install", assertSafeArg(app.name, "app")];
    if (request.file) args.push("--file", assertSafeArg(request.file, "file"));
    for (const [key, value] of Object.entries(request.settings ?? {})) {
      if (!SETTING_KEY.test(key)) return PolicyError.throw(`Invalid setting name: ${key}`);
      // eslint-disable-next-line no-control-regex
      if (/[\u0000-\u001f]/.test(value)) return PolicyError.throw(`Invalid value for ${key}`);
      if (value !== "") args.push("--set", `${key}=${value}`);
    }
    if (request.partner) args.push("--partner");
    if (request.from && request.from !== "Official") args.push("--from", assertSafeArg(request.from, "source"));
    if (request.launch) args.push("--launch");
    if (request.allowRemove) args.push("--allow-remove");
    if (request.removeFirst) args.push("--remove-first");
    if (request.newId) args.push("--new-id");
    args.push(...this.tvArgs());
    return this.queue("install", `Install ${app.name}`, args, true);
  }

  /** Installs an uploaded .wgt/.tpk by its upload id. */
  async installUpload(uploadId: string, label: string): Promise<JobSnapshot> {
    if (!UPLOAD_ID.test(uploadId)) return PolicyError.throw("Unknown upload");
    const args = ["install", join(this.config.uploadDir, uploadId), ...this.tvArgs()];
    return this.queue("install-file", `Install ${label}`, args, true);
  }

  /** Installs a package m7d built itself (e.g. the YouTube shim); `path` never comes from a request. */
  async installBuilt(path: string, label: string): Promise<JobSnapshot> {
    return this.queue("install-file", `Install ${label}`, ["install", path, ...this.tvArgs()], true);
  }

  /** Removes an app by its Tizen app id. */
  async uninstall(appId: string): Promise<JobSnapshot> {
    const args = ["uninstall", assertSafeArg(appId, "app id"), ...this.tvArgs()];
    return this.queue("uninstall", `Uninstall ${appId}`, args, false);
  }

  /** Updates every app with a newer catalog version, or only the named ones. */
  async update(apps: string[] | "all"): Promise<JobSnapshot> {
    const targets = apps === "all" ? ["--all"] : apps.map((app) => assertSafeArg(app, "app"));
    const title = apps === "all" ? "Update all apps" : `Update ${apps.join(", ")}`;
    return this.queue("update", title, ["update", ...targets, ...this.tvArgs()], false);
  }

  /** Deletes every package left in the TV's staging folder. */
  async clearLeftovers(): Promise<JobSnapshot> {
    return this.queue("leftovers-clear", "Clear install leftovers", ["leftovers", ...this.tvArgs(), "--clear"], false);
  }

  /** Deletes one file from the TV's staging folder. */
  async deleteLeftover(file: string): Promise<JobSnapshot> {
    const args = ["leftovers", ...this.tvArgs(), "--delete", assertSafeArg(file, "file")];
    return this.queue("leftovers-delete", `Delete leftover ${file}`, args, false);
  }

  /** Saves the TV's catalog apps to a profile (optionally with typed settings: keep private). */
  async saveProfile(name: string, withSettings: boolean): Promise<JobSnapshot> {
    if (!PROFILE_NAME.test(name)) return PolicyError.throw("Profile names may use letters, digits, - and _");
    await mkdir(this.config.profileDir, { recursive: true });
    const args = ["tv", "save", join(this.config.profileDir, `${name}.json`), ...this.tvArgs(), "--yes"];
    if (withSettings) args.push("--with-settings");
    return this.queue("profile-save", `Save TV profile ${name}`, args, false);
  }

  /** Installs a profile's apps the TV does not have (optionally only the named ones). */
  async restoreProfile(name: string, apps: string[]): Promise<JobSnapshot> {
    if (!PROFILE_NAME.test(name)) return PolicyError.throw("Unknown profile");
    const file = join(this.config.profileDir, `${name}.json`);
    const args = ["tv", "restore", file, ...apps.map((app) => assertSafeArg(app, "app")), ...this.tvArgs()];
    return this.queue("profile-restore", `Restore TV profile ${name}`, args, true);
  }

  /** Signs an uploaded package for this TV without installing it; download it afterwards. */
  async sign(uploadId: string, label: string): Promise<JobSnapshot> {
    if (!UPLOAD_ID.test(uploadId)) return PolicyError.throw("Unknown upload");
    await mkdir(this.config.signedDir, { recursive: true });
    const args = [
      "sign",
      join(this.config.uploadDir, uploadId),
      "-o",
      join(this.config.signedDir, uploadId),
      ...this.tvArgs(),
    ];
    return this.queue("sign", `Sign ${label}`, args, false);
  }

  /** Path of a signed package, or undefined for an unknown id. */
  signedPath(uploadId: string): string | undefined {
    return UPLOAD_ID.test(uploadId) ? join(this.config.signedDir, uploadId) : undefined;
  }

  /** The CLI's session logs (newest first). */
  async logs(): Promise<LogsResult> {
    return A2sService.unwrap(await this.cli.run<LogsResult>(["logs"], { timeoutMs: 30_000 }));
  }

  /** Text of one CLI session log, by its file name (must be one the CLI lists). */
  async logText(name: string): Promise<string> {
    const { logs } = await this.logs();
    const entry = logs.find((log) => log.name === name);
    if (!entry) return PolicyError.throw("Unknown log");
    return Bun.file(entry.path).text();
  }

  /** Repeats a job that stopped at a pre-install check, now with `--yes`. */
  async retryAnyway(jobId: string): Promise<JobSnapshot> {
    const job = this.jobs.get(jobId);
    const recipe = this.retryRecipes.get(jobId);
    if (!job || !recipe || !job.canRetryAnyway) return PolicyError.throw("This job cannot be retried");
    return this.queue(recipe.kind, `${recipe.title} (anyway)`, [...recipe.args, "--yes"], false);
  }
}
